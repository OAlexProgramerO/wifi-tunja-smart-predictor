"""Compatibility checks and criterion comparisons for immutable policy runs."""

from __future__ import annotations

from datetime import UTC, datetime
from math import isclose, isfinite
from typing import Any

REASON_EXPLANATIONS = {
    "RUN_PROVENANCE_MISSING": "A run report or experiment provenance is incomplete.",
    "SAME_RUN_SELECTED": "Two distinct policy evaluation runs are required.",
    "DIFFERENT_EXPERIMENTS": "Runs evaluate different saved experiments.",
    "DIFFERENT_POLICY_PROFILES": "Runs use different policy IDs.",
    "INCOMPATIBLE_TASKS": "Runs evaluate different task types.",
    "INCOMPATIBLE_DATASETS": "Synthetic dataset fingerprints or algorithms differ.",
    "SYNTHETIC_PROVENANCE_UNAVAILABLE": "Synthetic dataset provenance is missing or invalid.",
    "INCOMPATIBLE_EVALUATION_CONTEXT": "Evaluation split or chronological window differs.",
    "INCOMPATIBLE_CRITERIA": "Policy versions do not define the same metric/operator criteria.",
    "INCOMPATIBLE_METRIC_EVIDENCE": "Recorded values for shared criteria do not agree.",
    "INCOMPATIBLE_EVALUATOR_VERSION": "Runs were generated by different or unidentified application versions.",
}


def _parts(run: dict[str, Any]) -> tuple[dict[str, Any], dict[str, Any], dict[str, Any]]:
    report = run.get("report") if isinstance(run.get("report"), dict) else {}
    policy = report.get("policy") if isinstance(report.get("policy"), dict) else {}
    experiment = report.get("experiment") if isinstance(report.get("experiment"), dict) else {}
    return report, policy, experiment


def _criterion_map(report: dict[str, Any]) -> dict[tuple[str, str], dict[str, Any]]:
    rows = report.get("criteria")
    if not isinstance(rows, list):
        return {}
    result = {}
    for row in rows:
        if not isinstance(row, dict):
            continue
        metric, operator = row.get("metric"), row.get("operator")
        if isinstance(metric, str) and operator in {"gte", "lte"}:
            result[(metric, operator)] = row
    return result


def _compatibility_reasons(left: dict[str, Any], right: dict[str, Any]) -> list[str]:
    left_report, left_policy, left_experiment = _parts(left)
    right_report, right_policy, right_experiment = _parts(right)
    reasons = []
    if not left_report or not right_report or not left_experiment or not right_experiment:
        reasons.append("RUN_PROVENANCE_MISSING")
    if left.get("run_id") == right.get("run_id"):
        reasons.append("SAME_RUN_SELECTED")
    if left.get("experiment_id") != right.get("experiment_id"):
        reasons.append("DIFFERENT_EXPERIMENTS")
    if left.get("policy_id") != right.get("policy_id"):
        reasons.append("DIFFERENT_POLICY_PROFILES")
    if not left_report.get("project_version") or left_report.get(
        "project_version"
    ) != right_report.get("project_version"):
        reasons.append("INCOMPATIBLE_EVALUATOR_VERSION")
    if left_experiment.get("task") != right_experiment.get("task"):
        reasons.append("INCOMPATIBLE_TASKS")

    left_dataset = left_experiment.get("dataset")
    right_dataset = right_experiment.get("dataset")
    if not isinstance(left_dataset, dict) or not isinstance(right_dataset, dict):
        reasons.append("SYNTHETIC_PROVENANCE_UNAVAILABLE")
    else:
        for dataset in (left_dataset, right_dataset):
            fingerprint = dataset.get("fingerprint")
            if (
                dataset.get("kind") != "synthetic"
                or not isinstance(fingerprint, str)
                or len(fingerprint) != 64
                or any(char not in "0123456789abcdef" for char in fingerprint)
                or not dataset.get("fingerprint_algorithm")
            ):
                reasons.append("SYNTHETIC_PROVENANCE_UNAVAILABLE")
        if left_dataset.get("fingerprint") != right_dataset.get("fingerprint") or left_dataset.get(
            "fingerprint_algorithm"
        ) != right_dataset.get("fingerprint_algorithm"):
            reasons.append("INCOMPATIBLE_DATASETS")
    if left_experiment.get("evaluation_split") != right_experiment.get(
        "evaluation_split"
    ) or left_experiment.get("evaluation_window") != right_experiment.get("evaluation_window"):
        reasons.append("INCOMPATIBLE_EVALUATION_CONTEXT")
    if not isinstance(left_policy.get("version"), int) or not isinstance(
        right_policy.get("version"), int
    ):
        reasons.append("RUN_PROVENANCE_MISSING")

    left_criteria = _criterion_map(left_report)
    right_criteria = _criterion_map(right_report)
    if not left_criteria or set(left_criteria) != set(right_criteria):
        reasons.append("INCOMPATIBLE_CRITERIA")
    else:
        for key in left_criteria:
            left_value = left_criteria[key].get("value")
            right_value = right_criteria[key].get("value")
            if left_value is None or right_value is None:
                continue
            if not isinstance(left_value, (int, float)) or not isinstance(
                right_value, (int, float)
            ):
                reasons.append("INCOMPATIBLE_METRIC_EVIDENCE")
            elif (
                not isfinite(float(left_value))
                or not isfinite(float(right_value))
                or not isclose(float(left_value), float(right_value), rel_tol=0, abs_tol=1e-12)
            ):
                reasons.append("INCOMPATIBLE_METRIC_EVIDENCE")
    return sorted(set(reasons))


def compare_policy_evaluation_run_records(
    left: dict[str, Any], right: dict[str, Any]
) -> dict[str, Any]:
    """Compare outcomes for two runs only when experiment/policy context matches."""
    reasons = _compatibility_reasons(left, right)
    left_report, left_policy, _ = _parts(left)
    right_report, right_policy, _ = _parts(right)
    result = {
        "report_schema_version": "1.0",
        "generated_at_utc": datetime.now(UTC).isoformat(),
        "status": "INCOMPATIBLE" if reasons else "COMPATIBLE",
        "run_ids": [left.get("run_id"), right.get("run_id")],
        "context": {
            "experiment_id": left.get("experiment_id"),
            "policy_id": left.get("policy_id"),
            "left_policy_version": left_policy.get("version"),
            "right_policy_version": right_policy.get("version"),
        },
        "reasons": reasons,
        "reason_details": [
            {"code": reason, "message": REASON_EXPLANATIONS[reason]} for reason in reasons
        ],
        "criterion_comparisons": [],
        "interpretation": (
            "Incompatible policy run contexts; criterion comparisons are omitted."
            if reasons
            else "Threshold outcomes are compared for the same synthetic experiment and policy profile."
        ),
        "limitations": [
            "Comparison describes saved synthetic evaluation evidence only.",
            "It compares policy outcomes, not model quality or real-world performance.",
            "Policy runs and model artifacts are never modified or promoted.",
        ],
    }
    if reasons:
        return result

    left_criteria = _criterion_map(left_report)
    right_criteria = _criterion_map(right_report)
    comparisons = []
    partial = False
    for metric, operator in sorted(left_criteria):
        left_item = left_criteria[(metric, operator)]
        right_item = right_criteria[(metric, operator)]
        left_value, right_value = left_item.get("value"), right_item.get("value")
        left_status, right_status = left_item.get("status"), right_item.get("status")
        if (
            left_value is None
            or right_value is None
            or left_status == "INCONCLUSIVE"
            or right_status == "INCONCLUSIVE"
        ):
            partial = True
            assessment = "INCONCLUSIVE"
        elif left_status == right_status:
            assessment = "UNCHANGED"
        else:
            assessment = "OUTCOME_CHANGED"
        comparisons.append(
            {
                "metric": metric,
                "operator": operator,
                "left_threshold": left_item.get("threshold"),
                "right_threshold": right_item.get("threshold"),
                "threshold_changed": left_item.get("threshold") != right_item.get("threshold"),
                "left_value": left_value,
                "right_value": right_value,
                "left_result": left_status,
                "right_result": right_status,
                "assessment": assessment,
            }
        )
    result["criterion_comparisons"] = comparisons
    if partial:
        result["status"] = "PARTIAL"
    return result
